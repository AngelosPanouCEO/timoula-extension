export type I18nKey = Key;
const DICTS: Record<Lang, Record<Key, string>> = { el, en };

export function translate(lang: Lang, key: Key, params: Record<string, string | number> = {}): string {
  const template = DICTS[lang][key] ?? DICTS.el[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (k === 'product' ? PRODUCT.name : params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

export function detectLang(): Lang {
  const ui = typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage ? chrome.i18n.getUILanguage() : typeof navigator !== 'undefined' ? navigator.language : 'el';
  return ui.toLowerCase().startsWith('el') ? 'el' : 'en';
}
